// The app's sticker packs (the emoji panel's and the shop's "emoji paketleri"), as app/src/data/catalog.ts
// STICKER_PACKS has them: the app's test tests/server-catalog.test.ts fails when they drift. The pictures stay in the
// app (components/ReactionArt); a sticker travels as a token (app lib/stickers). The admins change any of these, and
// add packs and stickers of their own, from the panel without an app update (emoji.mjs, docs/EMOJI_YONETIMI.md).
// A pack sold in the shop is 'pack-<id>' (catalog.mjs SHOP keeps the sold ones' compiled prices for older apps).
//
// pack(id, name, price in coins (0: free), minimum VIP level (0: none), flags, stickers [id, name, emoji])
// flags: animated (the shop says so), roomOnly (Hamle: only in a room's panel, never sold), retired (no longer
// offered; its stickers still draw in old messages).

const pack = (id, name, price, minVip, flags, stickers) =>
  Object.freeze({
    id,
    name,
    price,
    minVip,
    animated: flags.includes('animated'),
    roomOnly: flags.includes('roomOnly'),
    retired: flags.includes('retired'),
    stickers: Object.freeze(stickers.map(([sid, sname, emoji]) => Object.freeze({ id: sid, name: sname, emoji }))),
  });

