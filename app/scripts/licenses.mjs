// Writes src/data/licenses.ts (the "Açık kaynak lisansları" screen) from package.json and node_modules.
// Run from app/ after changing dependencies:
//   node scripts/licenses.mjs
// Lists every runtime dependency with its version and the license declared in its own package.json, plus the
// full SIL Open Font License text of the bundled Plus Jakarta Sans font.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const readJson = (p) => JSON.parse(readFileSync(join(root, p), 'utf8'));

const repoUrl = (pkg) => {
  const raw = typeof pkg.repository === 'string' ? pkg.repository : pkg.repository?.url;
  if (raw) {
    const url = raw.replace(/^git\+/, '').replace(/^git:\/\//, 'https://').replace(/\.git$/, '');
    if (url.startsWith('https://')) return url;
    if (/^github:|^[\w-]+\/[\w.-]+$/.test(url)) return `https://github.com/${url.replace(/^github:/, '')}`;
  }
  return typeof pkg.homepage === 'string' ? pkg.homepage : undefined;
};

const app = readJson('package.json');
const entries = Object.keys(app.dependencies)
  .sort((a, b) => a.localeCompare(b))
  .map((name) => {
    const pkg = readJson(`node_modules/${name}/package.json`);
    const license = typeof pkg.license === 'string' ? pkg.license : pkg.license?.type ?? 'Belirtilmemiş';
    const url = repoUrl(pkg);
    return { name, version: pkg.version, license, ...(url ? { url } : {}) };
  });

const FONT_DIR = 'node_modules/@expo-google-fonts/plus-jakarta-sans';
const fontText = readFileSync(join(root, FONT_DIR, 'LICENSE_FONT'), 'utf8').trim();
const font = {
  family: 'Plus Jakarta Sans',
  copyright: fontText.split('\n')[0].trim(),
  license: 'SIL Open Font License 1.1',
  text: fontText,
};

const out = `// Generated by scripts/licenses.mjs from package.json and node_modules; do not edit by hand.
// Run \`node scripts/licenses.mjs\` from app/ after changing dependencies.

export type LicenseEntry = { name: string; version: string; license: string; url?: string };

export const LICENSES: LicenseEntry[] = ${JSON.stringify(entries, null, 2)};

export const FONT_LICENSE = ${JSON.stringify(font, null, 2)};
`;

writeFileSync(join(root, 'src/data/licenses.ts'), out);
console.log(`src/data/licenses.ts: ${entries.length} packages + ${font.family}`);
