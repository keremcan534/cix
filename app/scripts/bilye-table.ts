// Bilye Şelalesi: writes src/lib/bilye/table.ts from the board and the simulation.
//
//   node --experimental-strip-types --no-warnings --import ./tests/register.mjs scripts/bilye-table.ts
//
// For each launch strength it flies LAUNCHES balls and keeps (1) how many ended in each target, from which the
// rules take the odds (lib/bilye/rules), and (2) a handful of seeds per target, so the screen can show a real path
// into the target a round was drawn (lib/bilye/path). Run it again whenever the board or the physics change;
// tests/bilye.test.ts fails until the table matches them.
import fs from 'node:fs';
import path from 'node:path';

import { LANES, TARGETS } from '@/lib/bilye/board';
import { fly } from '@/lib/bilye/physics';

/** As lib/bilye/rules shareOut (not imported: rules reads the table this script writes). */
function shareOut(total: number, parts: number[]): number[] {
  const sum = parts.reduce((a, b) => a + b, 0);
  if (sum <= 0) return parts.map(() => 0);
  const out = parts.map((p) => (p * total - ((p * total) % sum)) / sum);
  const rest = parts.map((p, k) => ({ k, r: (p * total) % sum }));
  rest.sort((a, b) => b.r - a.r || a.k - b.k);
  let left = total - out.reduce((a, b) => a + b, 0);
  for (let i = 0; left > 0; i++, left--) out[rest[i].k]++;
  return out;
}

const LAUNCHES = 400_000;
/** Paths kept per target: enough that the same one is rarely seen twice in a row. */
const KEEP = 40;

const counts: Record<string, number[]> = {};
const seeds: Record<string, number[][]> = {};
for (const lane of LANES) {
  const c = new Array<number>(TARGETS.length).fill(0);
  const s = TARGETS.map((): number[] => []);
  for (let seed = 1; seed <= LAUNCHES; seed++) {
    const t = fly(lane, seed, false).target;
    if (t < 0) continue;
    c[t]++;
    if (s[t].length < KEEP) s[t].push(seed);
  }
  counts[lane] = c;
  seeds[lane] = s;
  console.log(lane, c.map((n) => ((100 * n) / LAUNCHES).toFixed(2)).join(' '), '| en az yol', Math.min(...s.map((x) => x.length)));
}

// The odds of each strength: the paying targets keep their share of the launches, scaled so that the strength pays
// back 40 % of the stakes at most (rounded down); the empty pockets share what is left in proportion to theirs.
const TOTAL = 100_000;
const tenths = TARGETS.map((t) => Math.round(t.mult * 10));
const weights: Record<string, number[]> = {};
for (const lane of LANES) {
  const c = counts[lane];
  const natural = c.reduce((a, n, k) => a + n * tenths[k], 0);
  const pay = c.map((n, k) => (tenths[k] ? (n * TOTAL * 4 - ((n * TOTAL * 4) % natural)) / natural : 0));
  const empty = shareOut(TOTAL - pay.reduce((a, b) => a + b, 0), c.map((n, k) => (tenths[k] ? 0 : n)));
  weights[lane] = pay.map((w, k) => w + empty[k]);
  const back = weights[lane].reduce((a, w, k) => a + w * tenths[k], 0) / (10 * TOTAL);
  const seen = natural / (10 * c.reduce((a, b) => a + b, 0));
  console.log(lane, 'doğal dönüş', seen.toFixed(4), '→ resmi', back.toFixed(5), '| ölçek', (0.4 / seen).toFixed(3));
}

const row = (xs: number[]) => `[${xs.join(', ')}]`;
const out = `// Generated by scripts/bilye-table.ts from lib/bilye/board and lib/bilye/physics. Do not edit by hand: run the
// script again when the board or the physics change (tests/bilye.test.ts checks that it still matches them).
import type { Lane } from '@/lib/bilye/board';

/** Balls flown per launch strength. */
export const LAUNCHES = ${LAUNCHES};
/** How many of them ended in each target (board TARGETS order). */
export const COUNTS: Record<Lane, readonly number[]> = {
${LANES.map((l) => `  ${l}: ${row(counts[l])},`).join('\n')}
};
/**
 * The odds of each launch strength, out of ${TOTAL} (lib/bilye/rules BILYE_TOTAL): the paying targets' share of the
 * launches scaled to pay back 40 % at most, the empty pockets taking the rest.
 */
export const WEIGHTS: Record<Lane, readonly number[]> = {
${LANES.map((l) => `  ${l}: ${row(weights[l])},`).join('\n')}
};
/** Seeds whose flight ends in each target. */
export const SEEDS: Record<Lane, readonly (readonly number[])[]> = {
${LANES.map((l) => `  ${l}: [\n${seeds[l].map((s) => `    ${row(s)},`).join('\n')}\n  ],`).join('\n')}
};
`;
const file = path.join(import.meta.dirname, '..', 'src', 'lib', 'bilye', 'table.ts');
fs.writeFileSync(file, out);
console.log('yazıldı:', path.relative(process.cwd(), file));
